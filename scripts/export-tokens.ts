/**
 * Color tokens for the UI kit: `npm run tokens` writes docs/tokens-export.md.
 *
 * Reads the :root (light) and .dark blocks of src/index.css, lets Chrome resolve every var() reference, and
 * writes each color token's final value in light and dark as sRGB hex and oklch. Shadow tokens are listed
 * with their resolved shadow color. Hex is what a browser paints (out-of-gamut oklch is clipped to sRGB).
 */
import fs from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright'

const ROOT = process.cwd()
const css = fs.readFileSync(path.join(ROOT, 'src', 'index.css'), 'utf8')
const block = (selector: string) => {
  const start = css.indexOf(selector)
  return css.slice(css.indexOf('{', start) + 1, css.indexOf('\n}', start))
}
const light = block(':root,\n.theme-light')
const dark = block('.dark,\n.theme-dark')

// Every custom property that holds a color (or a shadow), in declaration order
const names = [...light.matchAll(/^\s*--([\w-]+):\s*([^;]+);/gm)]
  .filter(([, name, value]) => /oklch|hsl|rgb|#|var\(/.test(value) && !/^font|^radius|^spacing|^tracking|^letter|^shadow-(offset|blur|spread|opacity)/.test(name))
  .map(([, name]) => name)

const browser = await chromium.launch({ channel: 'chrome' })
try {
  const page = await browser.newPage()
  await page.setContent(`<style>:root{${light}} .dark{${dark}}</style><div id="probe"></div>`)
  const read = (scheme: 'light' | 'dark') =>
    page.evaluate(
      ({ names, scheme }) => {
        document.documentElement.className = scheme === 'dark' ? 'dark' : ''
        const probe = document.getElementById('probe')!
        const ctx = document.createElement('canvas').getContext('2d', { willReadFrequently: true })!
        const toRgba = (color: string) => {
          ctx.clearRect(0, 0, 1, 1)
          ctx.fillStyle = color
          ctx.fillRect(0, 0, 1, 1)
          return [...ctx.getImageData(0, 0, 1, 1).data]
        }
        // sRGB → OKLab → OKLCH (Björn Ottosson's matrices)
        const toOklch = ([r, g, b]: number[]) => {
          const lin = (c: number) => ((c /= 255) <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
          const [R, G, B] = [lin(r), lin(g), lin(b)]
          const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B)
          const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B)
          const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B)
          const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
          const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
          const Bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
          const C = Math.hypot(A, Bb)
          const H = C < 0.0001 ? 0 : ((Math.atan2(Bb, A) * 180) / Math.PI + 360) % 360
          return `oklch(${L.toFixed(4)} ${C.toFixed(4)} ${H.toFixed(2)})`
        }
        const hex = (rgba: number[]) => '#' + rgba.slice(0, 3).map((v) => v.toString(16).padStart(2, '0')).join('')
        return names.map((name) => {
          const raw = getComputedStyle(document.documentElement).getPropertyValue(`--${name}`).trim()
          if (/^\d|px/.test(raw)) {
            // A shadow: report it with its color resolved
            probe.style.boxShadow = `var(--${name})`
            return { name, shadow: getComputedStyle(probe).boxShadow }
          }
          probe.style.color = `var(--${name})`
          const computed = getComputedStyle(probe).color
          const rgba = toRgba(computed)
          // Declared in oklch: keep the exact value; otherwise derive it from the painted sRGB
          const oklch = computed.startsWith('oklch') ? computed.replace(/\s*\/\s*1\)$/, ')') : toOklch(rgba)
          return { name, hex: hex(rgba), oklch, alpha: rgba[3] < 255 ? Math.round((rgba[3] / 255) * 100) / 100 : 1 }
        })
      },
      { names, scheme },
    )
  const [l, d] = [await read('light'), await read('dark')]

  type Row = { name: string; hex?: string; oklch?: string; alpha?: number; shadow?: string }
  const cell = (r: Row) => (r.shadow ? `\`${r.shadow}\`` : `\`${r.hex}\`${r.alpha !== 1 ? ` (α ${r.alpha})` : ''} · \`${r.oklch}\``)
  const groups: [string, (n: string) => boolean][] = [
    ['Surfaces and text', (n) => /^(background|foreground|card|popover)/.test(n)],
    ['Actions and states', (n) => /^(primary|secondary|muted|accent|destructive|ring|border|input)/.test(n)],
    ['Marginalia', (n) => /^(rating|band|track|placeholder|cover-shadow)/.test(n)],
    ['Charts (from the theme, unused by the app: its charts use --primary)', (n) => n.startsWith('chart')],
    ['Sidebar (from the theme, unused by the app)', (n) => n.startsWith('sidebar')],
    ['Shadows', (n) => n.startsWith('shadow')],
  ]
  const seen = new Set<string>()
  let md = `# Color tokens: final values

Generated by \`npm run tokens\` from \`src/index.css\` (theme v2, "Goodreads 1"). Every \`var()\` is resolved: this is what the app paints.

- **Hex** is sRGB as the browser renders it. **oklch** is the declared value, or, for tokens declared in another space (the shadow color), derived from the hex.
- Light = \`:root\` (and \`.theme-light\`), dark = \`.dark\` (and \`.theme-dark\`).
- Contrast rules for each pair are in [visual-system.md](visual-system.md).
`
  for (const [title, match] of groups) {
    const rows = l.filter((r) => match(r.name) && !seen.has(r.name))
    if (!rows.length) continue
    md += `\n## ${title}\n\n| Token | Light | Dark |\n|---|---|---|\n`
    for (const r of rows) {
      seen.add(r.name)
      md += `| \`--${r.name}\` | ${cell(r)} | ${cell(d.find((x) => x.name === r.name)!)} |\n`
    }
  }
  fs.writeFileSync(path.join(ROOT, 'docs', 'tokens-export.md'), md)
  console.log(`Wrote docs/tokens-export.md (${l.length} tokens)`)
} finally {
  await browser.close()
}

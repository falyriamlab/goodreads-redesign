type BookInput = Omit<Book, 'coverUrl' | 'synopsis' | 'editions' | 'isPublished' | 'trending' | 'avgRating' | 'ratingsCount'> &
  Partial<Pick<Book, 'synopsis' | 'editions' | 'isPublished' | 'trending'>>

function book(input: BookInput): Book {
  return {
    synopsis: null,
    editions: DEFAULT_EDITIONS,
    isPublished: true,
    trending: false,
    ...input,
    coverUrl: input.isbn13 ? `https://covers.openlibrary.org/b/isbn/${input.isbn13}-M.jpg?default=false` : null,
    avgRating: null,
    ratingsCount: null,
  }
}

